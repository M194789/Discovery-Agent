N_GT_RUNS = 3  # 每个 GT 题的运行次数
N_JUDGE_CALLS = 5  # 每次评估的 LLM 调用次数（多数投票，增加有效响应概率）
OUTPUT_ROOT = _project_root / "benchmark_results"
RESULTS_PATH = OUTPUT_ROOT / "reports" / "gt_judge_results.json"


# ---------------------------------------------------------------------------
# LLM-as-Judge Prompt
# ---------------------------------------------------------------------------

JUDGE_SYSTEM_PROMPT = """You are a scientific evaluation judge. Your task is to assess whether a set of hypotheses generated by an AI discovery system matches a known Ground Truth (GT) answer for a scientific problem.

You must classify the match as one of:
- **hit**: At least one hypothesis precisely captures the core mechanism(s) of the GT answer. The hypothesis must explicitly describe the same strategy/approach as the GT, not just mention tangentially related concepts.
- **partial**: The hypotheses touch upon concepts related to the GT answer but are incomplete, imprecise, or only partially cover the GT mechanisms. For example, mentioning "coating" without specifying "carbon coating", or mentioning "electrocatalysis" without specifying "single-atom" or "N₂ reduction".
- **miss**: No hypothesis has meaningful overlap with the GT answer's core mechanisms.

IMPORTANT GUIDELINES:
- Focus on MECHANISM MATCHING, not surface keyword overlap
- A hypothesis about "doping + DFT computation" does NOT match GT "nanostructuring + carbon coating"
- A hypothesis about "general electrocatalysis" PARTIALLY matches GT "single-atom electrocatalytic N₂ reduction"
- A hypothesis about "neural network beam prediction" MATCHES GT "AI-assisted beam prediction"
- Consider ALL hypotheses in the set, not just confirmed ones
- The hypothesis status (confirmed/active/refuted) is informational context but should not override mechanism matching

OUTPUT FORMAT: Return ONLY a valid JSON object:
```json
{
  "verdict": "hit|partial|miss",
  "rationale": "Brief explanation of why this verdict was chosen (2-3 sentences)",
  "matched_mechanisms": ["list of GT mechanisms that were matched by hypotheses"],
  "missing_mechanisms": ["list of GT mechanisms NOT covered by any hypothesis"]
}
```"""


# 假设截断参数
MAX_HYPOTHESES = 6  # 最多保留的假设数量
MAX_STMT_CHARS = 300  # 每条假设 statement 最大字符数


def build_judge_input(problem_id: str, hypotheses: list) -> str:
    """构造评估输入文本（含截断保护，防止超长输入导致 API 空响应）"""
    info = GT_PROBLEMS[problem_id]

    hyp_text = ""
    if not hypotheses:
        hyp_text = "(No final hypotheses produced in this run)"
    else:
        # 按 confidence 降序排列，保留 top-N
        sorted_hyps = sorted(hypotheses, key=lambda h: h.get("confidence", 0.0), reverse=True)
        truncated = sorted_hyps[:MAX_HYPOTHESES]
        if len(hypotheses) > MAX_HYPOTHESES:
            hyp_text += f"\n(Showing top {MAX_HYPOTHESES} of {len(hypotheses)} hypotheses by confidence)\n"
        for i, h in enumerate(truncated, 1):
            status = h.get("status", "unknown")
            conf = h.get("confidence", 0.0)
            stmt = h.get("statement", "")
            # 截断过长的 statement
            if len(stmt) > MAX_STMT_CHARS:
                stmt = stmt[:MAX_STMT_CHARS] + "..."
            hyp_text += f"\n{i}. [{status}] (confidence={conf:.2f}): {stmt}"

    return f"""## Scientific Problem
{info['statement']}

## Ground Truth Answer
{info['ground_truth']}

## GT Core Mechanisms
{chr(10).join('- ' + m for m in info['gt_mechanisms'])}

## System's Final Hypotheses
{hyp_text}

## Task
Assess whether the system's hypotheses match the Ground Truth answer.
Return your verdict as JSON."""


# ---------------------------------------------------------------------------
# LLM 调用与 JSON 解析
# ---------------------------------------------------------------------------

async def call_judge_once(problem_id: str, hypotheses: list) -> dict:
    """单次 LLM-as-Judge 调用"""
    input_text = build_judge_input(problem_id, hypotheses)

    response = await client.chat.completions.create(
        model=MODEL_NAME,
        messages=[
            {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
            {"role": "user", "content": input_text},
        ],
        temperature=0.3,
        max_tokens=1000,
    )

    output = response.choices[0].message.content or ""
    return parse_judge_output(output)


def parse_judge_output(output: str) -> dict:
    """多策略解析 LLM 输出为结构化 verdict"""
    cleaned = re.sub(r'^```(?:json)?\s*|\s*```$', '', output.strip())

    data = None

    # 策略1: 直接解析
    try:
        data = json.loads(cleaned)
    except json.JSONDecodeError:
        pass

    # 策略2: 括号匹配找完整 JSON 对象
    if data is None:
        brace_count = 0
        start_pos = -1
        end_pos = -1
        in_string = False
        for i, char in enumerate(cleaned):
            if char == '"' and (i == 0 or cleaned[i - 1] != '\\'):
                in_string = not in_string
            elif not in_string:
                if char == '{':
                    if start_pos == -1:
                        start_pos = i
                    brace_count += 1
                elif char == '}':
                    brace_count -= 1
                    if brace_count == 0 and start_pos != -1:
                        end_pos = i + 1
                        break
        if start_pos != -1 and end_pos != -1:
            try:
                data = json.loads(cleaned[start_pos:end_pos])
            except json.JSONDecodeError:
                pass

    # 策略3: 正则提取 verdict
    if data is None:
        verdict_match = re.search(
            r'"verdict"\s*:\s*"(hit|partial|miss)"', cleaned, re.IGNORECASE
        )
        if verdict_match:
            data = {"verdict": verdict_match.group(1).lower()}
            # 尝试提取 rationale
            rationale_match = re.search(
                r'"rationale"\s*:\s*"([^"]*)"', cleaned
            )
            if rationale_match:
                data["rationale"] = rationale_match.group(1)

    # 所有策略失败
    if data is None:
        # 最后尝试从文本中直接找 verdict 关键词
        output_lower = output.lower()
        if "verdict" in output_lower:
            if '"hit"' in output_lower or ": hit" in output_lower:
                data = {"verdict": "hit", "rationale": "Extracted from unstructured output"}
            elif '"partial"' in output_lower or ": partial" in output_lower:
                data = {"verdict": "partial", "rationale": "Extracted from unstructured output"}
            elif '"miss"' in output_lower or ": miss" in output_lower:
                data = {"verdict": "miss", "rationale": "Extracted from unstructured output"}

    if data is None:
        return {"verdict": "error", "rationale": "Failed to parse LLM output", "raw_output": output[:500]}

    # 验证 verdict 值
    verdict = data.get("verdict", "").lower()
    if verdict not in ("hit", "partial", "miss"):
        return {"verdict": "error", "rationale": f"Invalid verdict: {verdict}", "raw_output": output[:500]}

    return {
        "verdict": verdict,
        "rationale": data.get("rationale", ""),
        "matched_mechanisms": data.get("matched_mechanisms", []),
        "missing_mechanisms": data.get("missing_mechanisms", []),
    }


async def judge_single_run(problem_id: str, hypotheses: list) -> dict:
    """对单个 run 执行 3 次评估并取多数投票"""
    results = []
    for attempt in range(N_JUDGE_CALLS):
        try:
            result = await call_judge_once(problem_id, hypotheses)
            results.append(result)
            print(f"      Call {attempt+1}/{N_JUDGE_CALLS}: {result['verdict']}")
        except Exception as e:
            print(f"      Call {attempt+1}/{N_JUDGE_CALLS}: ERROR - {e}")
            results.append({"verdict": "error", "rationale": str(e)})

    # 多数投票
    verdicts = [r["verdict"] for r in results if r["verdict"] != "error"]
    if not verdicts:
        return {
            "final_verdict": "error",
            "rationale": "All 3 judge calls failed",
            "individual_results": results,
            "vote_distribution": {},
        }

    vote_counts = Counter(verdicts)
    final_verdict = vote_counts.most_common(1)[0][0]

    # 选取与最终 verdict 一致的最佳 rationale
    best_result = next(
        (r for r in results if r["verdict"] == final_verdict),
        results[0]
    )

    return {
        "final_verdict": final_verdict,
        "rationale": best_result.get("rationale", ""),
        "matched_mechanisms": best_result.get("matched_mechanisms", []),
        "missing_mechanisms": best_result.get("missing_mechanisms", []),
        "vote_distribution": dict(vote_counts),
        "individual_results": results,
    }


