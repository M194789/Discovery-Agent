# 主评估流程
# ---------------------------------------------------------------------------

def load_gt_hypotheses(problem_id: str, run_id: int) -> list:
    """从 GT 结果文件中加载最终假设"""
    domain = GT_PROBLEMS[problem_id]["domain"]
    result_path = OUTPUT_ROOT / domain / "gt" / f"{problem_id}_run{run_id}.json"

    if not result_path.exists():
        print(f"    WARNING: Result file not found: {result_path}")
        return []

    with open(result_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    # 优先使用 gt_assessment 中的 final_hypotheses
    gt_assessment = data.get("gt_assessment", {})
    hypotheses = gt_assessment.get("final_hypotheses", [])

    # 如果为空，尝试从 state_dump 最后一轮迭代中提取
    if not hypotheses:
        iterations = data.get("state_dump", {}).get("iterations", [])
        if iterations:
            last_iter = iterations[-1]
            hypotheses = last_iter.get("hypotheses", [])

    return hypotheses


async def run_evaluation(
    target_problem: Optional[str] = None,
    force: bool = False,
):
    """执行全部 GT 评估"""
    # 加载已有结果（增量模式：--force 只强制覆盖目标题，保留其他题的结果）
    existing_results = {}
    if RESULTS_PATH.exists():
        with open(RESULTS_PATH, "r", encoding="utf-8") as f:
            existing_results = json.load(f)

    results = existing_results.copy()
    results.setdefault("metadata", {
        "model": MODEL_NAME,
        "n_judge_calls": N_JUDGE_CALLS,
        "generated_at": datetime.now().isoformat(),
    })
    results.setdefault("evaluations", {})

    problems_to_eval = [target_problem] if target_problem else list(GT_PROBLEMS.keys())

    total_start = time.time()
    total_evaluated = 0

    print(f"\n{'='*60}")
    print(f"  GT LLM-as-Judge Evaluation")
    print(f"  Model: {MODEL_NAME} | Judge calls: {N_JUDGE_CALLS}")
    print(f"  Problems: {problems_to_eval}")
    print(f"{'='*60}\n")

    for pid in problems_to_eval:
        if pid not in GT_PROBLEMS:
            print(f"  ERROR: Unknown GT problem ID '{pid}'")
            continue

        info = GT_PROBLEMS[pid]
        print(f"\n  --- {pid} ({info['domain']}) ---")
        print(f"  GT: {info['ground_truth']}")

        results["evaluations"].setdefault(pid, {})

        for run_id in range(N_GT_RUNS):
            run_key = f"run{run_id}"

            # 增量：跳过已评估的
            if run_key in results["evaluations"][pid] and not force:
                existing_verdict = results["evaluations"][pid][run_key].get("final_verdict", "")
                if existing_verdict in ("hit", "partial", "miss"):
                    print(f"    run{run_id}: SKIP (existing verdict: {existing_verdict})")
                    continue

            # 加载假设
            hypotheses = load_gt_hypotheses(pid, run_id)
            n_hyps = len(hypotheses)
            print(f"    run{run_id}: Evaluating ({n_hyps} hypotheses)...")

            # 执行评估
            judge_result = await judge_single_run(pid, hypotheses)
            judge_result["n_hypotheses"] = n_hyps
            judge_result["timestamp"] = datetime.now().isoformat()

            results["evaluations"][pid][run_key] = judge_result
            total_evaluated += 1

            verdict = judge_result["final_verdict"]
            votes = judge_result.get("vote_distribution", {})
            print(f"    run{run_id}: VERDICT = {verdict.upper()} (votes: {votes})")

    # 生成汇总统计
    summary = {}
    for pid in GT_PROBLEMS:
        pid_results = results["evaluations"].get(pid, {})
        verdicts = [
            pid_results[f"run{i}"]["final_verdict"]
            for i in range(N_GT_RUNS)
            if f"run{i}" in pid_results and pid_results[f"run{i}"].get("final_verdict") in ("hit", "partial", "miss")
        ]
        summary[pid] = {
            "hit_count": verdicts.count("hit"),
            "partial_count": verdicts.count("partial"),
            "miss_count": verdicts.count("miss"),
            "total_evaluated": len(verdicts),
            "hit_rate": f"{verdicts.count('hit')}/{len(verdicts)}" if verdicts else "0/0",
        }

    results["summary"] = summary
    results["metadata"]["last_updated"] = datetime.now().isoformat()
    results["metadata"]["total_evaluated"] = total_evaluated

    # 保存结果
    RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(RESULTS_PATH, "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2, ensure_ascii=False)

    # 打印汇总
    elapsed = time.time() - total_start
    print(f"\n{'='*60}")
    print(f"  Evaluation Complete ({elapsed:.0f}s)")
    print(f"  Evaluated: {total_evaluated} runs")
    print(f"  Results: {RESULTS_PATH}")
    print(f"\n  Summary:")
    for pid, s in summary.items():
        print(f"    {pid}: hit={s['hit_count']} partial={s['partial_count']} miss={s['miss_count']}")
    print(f"{'='*60}\n")

    return results


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description="GT LLM-as-Judge 深度评估")
    parser.add_argument("--problem", default=None, help="仅评估指定 GT 题 (A-GT/B-GT/C-GT)")
    parser.add_argument("--force", action="store_true", help="强制重新评估（忽略已有结果）")
    args = parser.parse_args()

    asyncio.run(run_evaluation(
        target_problem=args.problem,
        force=args.force,
    ))


if __name__ == "__main__":
    main()
